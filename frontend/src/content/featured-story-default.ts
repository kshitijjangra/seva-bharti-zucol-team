// Plain paragraphs → Lexical rich-text JSON; "**word**" becomes bold (highlight).
function lexical(paragraphs: readonly string[]): Story["story"] {
  return {
    root: {
      type: "root",
      version: 1,
      direction: "ltr",
      format: "",
      indent: 0,
      children: paragraphs.map((text) => ({
        type: "paragraph",
        version: 1,
        direction: "ltr",
        format: "",
        indent: 0,
        textFormat: 0,
        textStyle: "",
        children: text
          .split(/(\*\*[^*]+\*\*)/)
          .filter(Boolean)
          .map((part) => {
            const bold = part.startsWith("**") && part.endsWith("**");
            return { type: "text", version: 1, detail: 0, format: bold ? 1 : 0, mode: "normal", style: "", text: bold ? part.slice(2, -2) : part };
          }),
      })),
    },
  } as Story["story"];
}

